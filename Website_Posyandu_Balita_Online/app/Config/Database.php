    public function __construct()
    {
        parent::__construct();

        // Ensure that we always set the database group to 'tests' if
        // we are currently running an automated test suite, so that
        // we don't overwrite live data on accident.
        if (ENVIRONMENT === 'testing') {
            $this->defaultGroup = 'tests';
        }

        // DBDebug membuat pesan error SQL menampilkan query yang sedang jalan.
        // Pernah membuat hash password bcrypt ikut tertulis ke writable/logs
        // saat sebuah INSERT gagal. Debug query hanya boleh menyala di
        // development; di staging/production selalu dimatikan.
        if (! in_array(ENVIRONMENT, ['development', 'testing'], true)) {
            $this->default['DBDebug'] = false;
            $this->tests['DBDebug']   = false;
        }
    }
